#!/usr/bin/env node
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { homedir } from 'node:os';
import { ConfigPlan, TOML } from './lib/config.mjs';
import { managementTasks, migrateAgents } from './lib/tooling.mjs';
const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
try {
  if (process.argv.length !== 2) throw new Error('Usage: node scripts/setup-tooling.mjs');
  migrateAgents();
  const plan = new ConfigPlan();
  const config = process.env.MISE_CONFIG_DIR || join(process.env.XDG_CONFIG_HOME || join(homedir(), '.config'), 'mise');
  plan.set(join(config, 'conf.d/20-dotfiles-tasks.toml'), '# Generated by dotfiles setup.\n' + TOML.stringify({ tasks: managementTasks(root) }));
  plan.apply();
} catch (error) { console.error(error.message); process.exitCode = 1; }
