#!/usr/bin/env node
import { existsSync, readFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { homedir } from 'node:os';
import { fileURLToPath } from 'node:url';
import { isDeepStrictEqual } from 'node:util';
import { ConfigPlan, TOML, readJson, parseTomlConfig } from './lib/config.mjs';

export const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
export function miseDirectory(home) {
  return process.env.MISE_CONFIG_DIR || join(process.env.XDG_CONFIG_HOME || join(home, '.config'), 'mise');
}
export function toolDefaults() {
  const tools = TOML.parse(readFileSync(join(root, 'mise/.config/mise/config.toml'), 'utf8')).tools;
  // Omarchy supplies these native mise launchers, including its account dispatchers.
  for (const [from, to] of Object.entries({ 'npm:@openai/codex': 'codex', 'npm:@earendil-works/pi-coding-agent': 'pi' })) {
    tools[to] = tools[from];
    delete tools[from];
  }
  tools.claude = 'latest';
  tools.railway = 'latest';
  // Native Omarchy launchers run `mise use -g pi` and select latest on every launch.
  tools.pi = { ...tools.pi, version: 'latest' };
  return tools;
}
export function configureTools(plan) {
  const file = join(miseDirectory(plan.home), 'conf.d/10-dotfiles.toml');
  const defaults = { tools: toolDefaults() };
  // Native launchers may reformat the generated fragment; compare declarations.
  if (plan.text(file) && isDeepStrictEqual(parseTomlConfig(file, plan.text(file)), defaults)) return;
  plan.set(file, '# Generated by dotfiles. Existing global config.toml and project settings take precedence.\n' + TOML.stringify(defaults));
}
export function configureClients(plan) {
  const home = plan.home;
  const servers = JSON.parse(readFileSync(join(root, 'ai/pi/mcp.json'), 'utf8')).mcpServers;
  plan.tomlMcp(join(home, '.codex/config.toml'), servers);
  plan.json(join(home, '.claude.json'), { mcpServers: Object.fromEntries(Object.entries(servers).map(([name, cfg]) => [name, { type: 'stdio', ...cfg }])) }, { entries: ['mcpServers'] });
  const opencode = join(home, '.config/opencode');
  const configs = ['opencode.json', 'opencode.jsonc'].map(name => join(opencode, name)).filter(existsSync);
  if (!configs.length) configs.push(join(opencode, 'opencode.json'));
  const mcp = Object.fromEntries(Object.entries(servers).map(([name, cfg]) => [name, {
    type: 'local', command: [cfg.command, ...(cfg.args || [])], enabled: true,
    ...(cfg.env ? { environment: cfg.env } : {}),
  }]));
  for (const file of configs) plan.json(file, { mcp }, { entries: ['mcp'] });
  plan.json(join(home, '.pi/agent/mcp.json'), { mcpServers: servers }, { entries: ['mcpServers'] });
  const piDefaults = JSON.parse(readFileSync(join(root, 'ai/pi/settings.json'), 'utf8'));
  const piTheme = join(home, '.local/state/omarchy/current/theme/pi.json');
  if (existsSync(piTheme)) {
    const { text } = readJson(piTheme);
    plan.set(join(home, '.pi/agent/themes/omarchy-system.json'), text);
    piDefaults.theme = 'omarchy-system';
  }
  plan.json(join(home, '.pi/agent/settings.json'), piDefaults, { packages: true });
}
export function configureShell(plan) {
  // Source the checkout directly so edits follow Git, without replacing any Omarchy config.
  const source = join(root, 'omarchy/bashrc');
  const quoted = `'${source.replaceAll("'", "'\\''")}'`;
  plan.block(join(plan.home, '.bashrc'), 'omarchy', `[[ -r ${quoted} ]] && source ${quoted}`);
}
export function configureInstructions(plan) {
  const content = readFileSync(join(root, 'ai/.agents/AGENTS.md'), 'utf8');
  for (const name of ['.agents/AGENTS.md', '.codex/AGENTS.md', '.pi/agent/AGENTS.md']) {
    const file = join(plan.home, name);
    // Existing canonical links already track the repository; don't edit their source.
    if (existsSync(file) && readFileSync(file, 'utf8') === content) continue;
    plan.block(file, 'working-agreements', content);
  }
  const claude = join(plan.home, '.claude/CLAUDE.md');
  if (!plan.text(claude).split('\n').includes('@~/.agents/AGENTS.md')) {
    plan.block(claude, 'working-agreements', '@~/.agents/AGENTS.md');
  }
}
export function configuration(home = homedir(), { toolsOnly = false } = {}) {
  const plan = new ConfigPlan(home);
  configureTools(plan);
  if (!toolsOnly) {
    configureClients(plan);
    configureShell(plan);
    configureInstructions(plan);
  }
  return plan;
}
if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try {
    const argv = process.argv.slice(2);
    if (argv.length === 1 && argv[0] === '--list-tools') {
      console.log(Object.keys(toolDefaults()).join('\n'));
      process.exit(0);
    }
    if (argv.length === 2 && argv[0] === '--browser') {
      const plan = new ConfigPlan();
      plan.json(join(homedir(), '.agent-browser/config.json'), { executablePath: argv[1] });
      plan.apply();
      process.exit(0);
    }
    const args = new Set(argv);
    if ([...args].some(arg => !['--tools-only', '--check'].includes(arg))) throw new Error('Usage: node scripts/setup-omarchy.mjs [--tools-only] [--check] | --list-tools | --browser PATH');
    if (process.env.MISE_GLOBAL_CONFIG_FILE) throw new Error('Unset MISE_GLOBAL_CONFIG_FILE so mise can load its conf.d fragments');
    configuration(homedir(), { toolsOnly: args.has('--tools-only') }).apply({ check: args.has('--check') });
    console.log(args.has('--check') ? 'Omarchy configuration checks passed.' : 'Omarchy configuration merged. Existing settings and instructions retained.');
  } catch (error) { console.error(error.message); process.exitCode = 1; }
}
